def instance_conns(text, head):
    start = text.index(head) + len(head)
    end = text.index(");", start)
    return dict(re.findall(r"\.(\w+)\((.*?)\)\s*[,\n]", text[start:end] + "\n"))


def add_probe(text):
    conns = instance_conns(text, CTRL_INST)
    lines = []
    for p, src in PROBE.items():
        if src.startswith("="):
            expr = src[1:]
        elif src in conns:
            expr = conns[src]
        else:
            sys.exit(f"controller port {src} not connected in serdes.v")
        lines.append(f"    .{p}({expr})")
    inst = ("\nown_pcie_probe own_pcie_probe_inst (\n" + ",\n".join(lines)
            + ",\n    .pages(own_pcie_probe_o)\n);\n")
    m = re.search(r"module SerDes_Top \(", text)
    text = text[: m.end()] + "own_pcie_probe_o, " + text[m.end():]
    hdr_end = text.index(";", m.end()) + 1
    text = text[:hdr_end] + "\noutput [3071:0] own_pcie_probe_o;\n" + text[hdr_end:]
    k = text.rindex("endmodule")
    return text[:k] + inst + text[k:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--own", action="store_true")
    ap.add_argument("--probe", action="store_true")
    ap.add_argument("src")
    ap.add_argument("out")
    a = ap.parse_args()
    text = open(a.src).read()
    for head in (CTRL_INST, ARB_INST):
        if text.count(head) != 1:
            sys.exit(f"{a.src}: expected one '{head}'")
    if a.probe:
        text = add_probe(text)
    if a.own:
        text = text.replace(CTRL_INST, "own_pcie_ctrl PCIE_Controller_Top_inst (")
        text = text.replace(ARB_INST, "own_upar_arbiter #(.DRP_NUM(8)) upar_arbiter_wrap_SerDes_Top_inst (")
    with open(a.out, "w") as f:
        f.write(f"// Generated by own_pcie/tools/gen_serdes.py {' '.join(sys.argv[1:])}\n")
        f.write(text)


if __name__ == "__main__":
    main()
