#!/usr/bin/env python3
"""Rewrite Gowin's SerDes_Top for own_pcie.

  gen_serdes.py [--own] [--probe] <vendor serdes.v> <out.v>

serdes.v is Gowin's generated (plain) wrapper around GTR12_QUAD, GTR12_UPAR,
GTR12_PMAC and the two encrypted soft blocks.

  --own    PCIE_Controller_Top -> own_pcie_ctrl, upar_arbiter_wrap ->
           own_upar_arbiter. Module name and ports stay, so board_top is
           untouched.
  --probe  add own_pcie_probe watching the controller's ports and the UPAR
           bus, on a new output own_pcie_probe_o[3071:0] (96 JTAG pages).
"""

